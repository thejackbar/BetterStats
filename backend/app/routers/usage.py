"""Usage breadcrumbs — endpoints.

- POST /usage/event: public beacon for frontend SPA route changes.
  Marketing pages, public yearbooks, in-app routes — everything the
  user sees that doesn't naturally hit its own API.
- GET /club-admin/usage/recent: super-admin only — latest events.
- GET /club-admin/usage/summary: top-level counters for the window.
- GET /club-admin/usage/timeseries: hits per bucket for the window.
- GET /club-admin/usage/top-routes: aggregated route counts.
- GET /club-admin/usage/top-users: most active users.
- GET /club-admin/usage/by-feature: rolled-up feature buckets
  (Players, Yearbooks, Marketing, etc.) — coarser than top-routes.
- GET /club-admin/usage/by-role: events split by user role.

API-call events come from the middleware in app.main; the beacon writes
the page-view events.

All admin views accept a `role` query param that filters to events
generated by users of that role (super_admin / club_admin / club_member
/ anon for logged-out hits).
"""
from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, Depends, Request
from pydantic import BaseModel
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.db import User, get_db
from app.routers.auth import require_super_admin
from app.services.usage_tracker import record_event

router = APIRouter(tags=["usage"])


# Highest-priority role wins when a user has multiple memberships.
# Anonymous events (no user_id) bucket as 'anon'.
ALLOWED_ROLES = ("super_admin", "club_admin", "club_member", "anon")

# Subquery that resolves a user to their single highest-priority role.
# LATERAL so it picks one row per user; ordered super > admin > member.
_USER_ROLE_JOIN = """
LEFT JOIN LATERAL (
    SELECT role
    FROM club_memberships
    WHERE user_id = ue.user_id
    ORDER BY CASE role
        WHEN 'super_admin'  THEN 0
        WHEN 'club_admin'   THEN 1
        WHEN 'club_member'  THEN 2
        ELSE 3
    END
    LIMIT 1
) cm ON ue.user_id IS NOT NULL
"""


def _role_filter(role: Optional[str]) -> str:
    """SQL fragment to AND into the WHERE clause for a role filter.

    Empty string when no role filter — caller already has a base
    `WHERE created_at >= …` so this is always combined with AND.
    """
    if role not in ALLOWED_ROLES:
        return ""
    if role == "anon":
        return "AND ue.user_id IS NULL"
    return "AND cm.role = :role_filter"


def _role_params(role: Optional[str]) -> dict:
    if role in ALLOWED_ROLES and role != "anon":
        return {"role_filter": role}
    return {}


# ─── Feature categorisation (Python-side, after group-by route) ──────────────

def _categorise(route: Optional[str], path: Optional[str], event_type: str) -> str:
    s = (route or path or "").lower()
    if not s:
        return "Other"
    if event_type == "page_view":
        if s in ("/", "/features", "/pricing", "/about", "/contact",
                 "/faq", "/terms", "/privacy"):
            return "Marketing"
        if s.startswith("/blog"):
            return "Marketing — Blog"
        if s.startswith("/login"):
            return "Auth pages"
        if s.startswith("/admin"):
            return "Admin pages"
        if s.startswith("/players/"):
            return "Player profiles"
        if (s.startswith("/games/") or s.startswith("/match/")
                or s.startswith("/scorecards/")):
            return "Match pages"
        if "/yearbook" in s:
            return "Yearbooks"
        if "/leaderboard" in s:
            return "Leaderboard"
        if "/statlab" in s:
            return "StatLab"
        if "/records" in s:
            return "Records"
        if "/compare" in s:
            return "Player comparison"
        if "/dashboard" in s:
            return "Club dashboard"
        return "Other pages"
    # API
    if s.startswith("/auth"):
        return "Auth"
    if "/yearbook" in s:
        return "Yearbooks"
    if "/club-admin/players" in s or s.startswith("/players"):
        return "Players"
    if s.startswith("/games") or s.startswith("/scorecards"):
        return "Matches"
    if "/leaderboard" in s:
        return "Leaderboard"
    if "/statlab" in s:
        return "StatLab"
    if "/records" in s:
        return "Records"
    if "/sync" in s or "hard-refresh" in s:
        return "Sync / Refresh"
    if s.startswith("/club-admin"):
        return "Admin actions"
    if s.startswith("/organisations"):
        return "Organisations"
    if s.startswith("/usage"):
        return "Usage tracking"
    return "Other API"


# ─── Public beacon ───────────────────────────────────────────────────────────

class PageViewIn(BaseModel):
    path: str
    referer: Optional[str] = None
    name: Optional[str] = None


@router.post("/usage/event")
async def post_event(payload: PageViewIn, request: Request):
    """Anonymous SPA page-view beacon."""
    from app.main import _decode_user_id, _client_ip  # avoid import cycle

    await record_event(
        event_type="page_view",
        method="GET",
        path=payload.path or "/",
        route=payload.name,
        status=200,
        user_id=_decode_user_id(request),
        ip=_client_ip(request),
        user_agent=request.headers.get("user-agent"),
        referer=payload.referer or request.headers.get("referer"),
    )
    return {"ok": True}


# ─── Super-admin views ───────────────────────────────────────────────────────

@router.get("/club-admin/usage/summary")
async def summary(
    days: int = 7,
    role: Optional[str] = None,
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    days = max(1, min(days, 365))
    params: dict = {"days": days, **_role_params(role)}
    extra = []
    if event_type:
        extra.append("AND ue.event_type = :etype")
        params["etype"] = event_type
    extras = "\n".join(extra) + " " + _role_filter(role)
    row = await db.execute(
        text(
            f"""
            SELECT
                COUNT(*)                                                            AS total,
                COUNT(*) FILTER (WHERE ue.event_type = 'api')                       AS api_hits,
                COUNT(*) FILTER (WHERE ue.event_type = 'page_view')                 AS page_views,
                COUNT(DISTINCT ue.user_id) FILTER (WHERE ue.user_id IS NOT NULL)    AS unique_users,
                COUNT(DISTINCT ue.ip_hash) FILTER (WHERE ue.ip_hash IS NOT NULL)    AS unique_ips
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {extras}
            """
        ),
        params,
    )
    r = row.mappings().first()
    return {
        "days": days,
        "total": int(r["total"] or 0),
        "api_hits": int(r["api_hits"] or 0),
        "page_views": int(r["page_views"] or 0),
        "unique_users": int(r["unique_users"] or 0),
        "unique_ips": int(r["unique_ips"] or 0),
    }


@router.get("/club-admin/usage/timeseries")
async def timeseries(
    days: int = 7,
    role: Optional[str] = None,
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Hits per bucket. Bucket = hour for 24h window, day for >24h."""
    days = max(1, min(days, 365))
    bucket = "hour" if days <= 1 else "day"
    params: dict = {"days": days, **_role_params(role)}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                date_trunc('{bucket}', ue.created_at) AS bucket,
                COUNT(*) FILTER (WHERE ue.event_type = 'api')        AS api_hits,
                COUNT(*) FILTER (WHERE ue.event_type = 'page_view')  AS page_views,
                COUNT(*) AS total
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            {_role_filter(role)}
            GROUP BY bucket
            ORDER BY bucket ASC
            """
        ),
        params,
    )
    return {
        "bucket": bucket,
        "points": [
            {
                "bucket": r["bucket"].isoformat() if r["bucket"] else None,
                "api_hits": int(r["api_hits"] or 0),
                "page_views": int(r["page_views"] or 0),
                "total": int(r["total"] or 0),
            }
            for r in rows.mappings().all()
        ],
    }


@router.get("/club-admin/usage/by-feature")
async def by_feature(
    days: int = 7,
    role: Optional[str] = None,
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Group routes/paths into feature buckets. Bucketing is Python-side
    so the SQL stays readable; the data volume per window is small."""
    days = max(1, min(days, 365))
    params: dict = {"days": days, **_role_params(role)}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                ue.route,
                ue.path,
                ue.event_type,
                COUNT(*) AS hits
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            {_role_filter(role)}
            GROUP BY ue.route, ue.path, ue.event_type
            """
        ),
        params,
    )
    buckets: dict[str, int] = {}
    for r in rows.mappings().all():
        feat = _categorise(r["route"], r["path"], r["event_type"])
        buckets[feat] = buckets.get(feat, 0) + int(r["hits"] or 0)
    return sorted(
        [{"feature": k, "hits": v} for k, v in buckets.items()],
        key=lambda x: x["hits"],
        reverse=True,
    )


@router.get("/club-admin/usage/by-role")
async def by_role(
    days: int = 7,
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Hit count grouped by the user's role (incl. anon)."""
    days = max(1, min(days, 365))
    params: dict = {"days": days}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                COALESCE(cm.role, 'anon') AS role,
                COUNT(*) AS hits,
                COUNT(DISTINCT ue.user_id) FILTER (WHERE ue.user_id IS NOT NULL) AS unique_users
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            GROUP BY COALESCE(cm.role, 'anon')
            ORDER BY hits DESC
            """
        ),
        params,
    )
    return [
        {
            "role": r["role"],
            "hits": int(r["hits"] or 0),
            "unique_users": int(r["unique_users"] or 0),
        }
        for r in rows.mappings().all()
    ]


@router.get("/club-admin/usage/top-routes")
async def top_routes(
    days: int = 7,
    limit: int = 30,
    role: Optional[str] = None,
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    days = max(1, min(days, 365))
    limit = max(1, min(limit, 200))
    params: dict = {"days": days, "lim": limit, **_role_params(role)}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                COALESCE(ue.route, ue.path) AS route_key,
                ue.event_type,
                COUNT(*) AS hits,
                COUNT(DISTINCT ue.user_id) FILTER (WHERE ue.user_id IS NOT NULL) AS unique_users,
                COUNT(DISTINCT ue.ip_hash) FILTER (WHERE ue.ip_hash IS NOT NULL) AS unique_ips,
                MAX(ue.created_at) AS last_hit
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            {_role_filter(role)}
            GROUP BY route_key, ue.event_type
            ORDER BY hits DESC
            LIMIT :lim
            """
        ),
        params,
    )
    return [
        {
            "route": r["route_key"],
            "event_type": r["event_type"],
            "hits": int(r["hits"] or 0),
            "unique_users": int(r["unique_users"] or 0),
            "unique_ips": int(r["unique_ips"] or 0),
            "last_hit": r["last_hit"].isoformat() if r["last_hit"] else None,
        }
        for r in rows.mappings().all()
    ]


@router.get("/club-admin/usage/top-users")
async def top_users(
    days: int = 7,
    limit: int = 30,
    role: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    days = max(1, min(days, 365))
    limit = max(1, min(limit, 200))
    params: dict = {"days": days, "lim": limit, **_role_params(role)}
    rows = await db.execute(
        text(
            f"""
            SELECT
                ue.user_id,
                u.email AS user_email,
                u.display_name AS user_display_name,
                cm.role AS user_role,
                COUNT(*) AS hits,
                COUNT(DISTINCT COALESCE(ue.route, ue.path)) AS unique_routes,
                MAX(ue.created_at) AS last_hit
            FROM usage_events ue
            LEFT JOIN users u ON u.id = ue.user_id
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
              AND ue.user_id IS NOT NULL
              {_role_filter(role)}
            GROUP BY ue.user_id, u.email, u.display_name, cm.role
            ORDER BY hits DESC
            LIMIT :lim
            """
        ),
        params,
    )
    return [
        {
            "user_id": str(r["user_id"]) if r["user_id"] else None,
            "user_email": r["user_email"],
            "user_display_name": r["user_display_name"],
            "user_role": r["user_role"],
            "hits": int(r["hits"] or 0),
            "unique_routes": int(r["unique_routes"] or 0),
            "last_hit": r["last_hit"].isoformat() if r["last_hit"] else None,
        }
        for r in rows.mappings().all()
    ]


@router.get("/club-admin/usage/recent")
async def recent_events(
    limit: int = 200,
    role: Optional[str] = None,
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    limit = max(1, min(limit, 1000))
    params: dict = {"lim": limit, **_role_params(role)}
    extras = []
    if event_type:
        extras.append("AND ue.event_type = :etype")
        params["etype"] = event_type
    # _role_filter starts with AND; recent has its own WHERE 1=1 base so any
    # combination works.
    extras_sql = "\n".join(extras) + " " + _role_filter(role)
    rows = await db.execute(
        text(
            f"""
            SELECT
                ue.id, ue.created_at, ue.event_type, ue.method, ue.path,
                ue.route, ue.status, ue.duration_ms, ue.user_id,
                ue.ip_hash, ue.referer,
                u.email AS user_email, u.display_name AS user_display_name,
                cm.role AS user_role
            FROM usage_events ue
            LEFT JOIN users u ON u.id = ue.user_id
            {_USER_ROLE_JOIN}
            WHERE 1=1
            {extras_sql}
            ORDER BY ue.created_at DESC
            LIMIT :lim
            """
        ),
        params,
    )
    return [
        {
            "id": r["id"],
            "created_at": r["created_at"].isoformat() if r["created_at"] else None,
            "event_type": r["event_type"],
            "method": r["method"],
            "path": r["path"],
            "route": r["route"],
            "status": r["status"],
            "duration_ms": r["duration_ms"],
            "user_id": str(r["user_id"]) if r["user_id"] else None,
            "user_email": r["user_email"],
            "user_display_name": r["user_display_name"],
            "user_role": r["user_role"],
            "ip_hash": r["ip_hash"],
            "referer": r["referer"],
        }
        for r in rows.mappings().all()
    ]
