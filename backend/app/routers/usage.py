_UUID_RE = re.compile(
    r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}",
    re.IGNORECASE,
)


# Highest-priority role wins when a user has multiple memberships.
# Anonymous events (no user_id) bucket as 'anon'.
ALLOWED_ROLES = ("super_admin", "club_admin", "club_member", "anon")

# Subquery that resolves a user to their single highest-priority role.
# LATERAL so it picks one row per user; ordered super > admin > member.
_USER_ROLE_JOIN = """
LEFT JOIN LATERAL (
    SELECT role
    FROM club_memberships
    WHERE user_id = ue.user_id
    ORDER BY CASE role
        WHEN 'super_admin'  THEN 0
        WHEN 'club_admin'   THEN 1
        WHEN 'club_member'  THEN 2
        ELSE 3
    END
    LIMIT 1
) cm ON ue.user_id IS NOT NULL
"""


def _normalise_roles(roles: Optional[list[str]]) -> list[str]:
    """Validate + dedupe an incoming list of role filter values.

    Accepts either a real list (FastAPI multi-`?role=` form) or a single
    comma-separated string for convenience.
    """
    if not roles:
        return []
    out: list[str] = []
    for r in roles:
        if r is None:
            continue
        for part in str(r).split(","):
            part = part.strip()
            if part in ALLOWED_ROLES and part not in out:
                out.append(part)
    return out


def _role_filter(roles: list[str]) -> str:
    """SQL fragment to AND into the WHERE clause for a multi-role filter.

    Empty string when no role filter. When `anon` is in the list it OR's
    a `user_id IS NULL` branch with the named-role IN (...) branch.
    """
    if not roles:
        return ""
    named = [r for r in roles if r != "anon"]
    include_anon = "anon" in roles
    if named and include_anon:
        return "AND (cm.role = ANY(:role_filter) OR ue.user_id IS NULL)"
    if named:
        return "AND cm.role = ANY(:role_filter)"
    # anon only
    return "AND ue.user_id IS NULL"


def _role_params(roles: list[str]) -> dict:
    named = [r for r in roles if r != "anon"]
    if named:
        return {"role_filter": named}
    return {}


# ─── Visitor identity ────────────────────────────────────────────────────────
# A visitor is keyed by the first-party `visitor_id` (a random UUID the SPA
# keeps in localStorage) when present, falling back to the hashed IP for legacy
# rows written before visitor_id existed. This single expression is reused
# across the visitor/lead views so "returning" is computed the same way
# everywhere — and survives an IP change, which the hash alone could not.
_VKEY = "COALESCE(ue.visitor_id::text, ue.ip_hash)"

# Page paths that signal buying intent — a visit here is a warm lead.
_INTENT_CONTACT = "split_part(ue.path, '?', 1) ~* '^/contact(/|$)'"
_INTENT_PRICING = "split_part(ue.path, '?', 1) ~* '^/pricing(/|$)'"


def _parse_device(ua: Optional[str]) -> dict:
    """Coarse device read from the user-agent. Good enough to tell a phone
    from a laptop and name the browser — we don't ship a full UA database."""
    s = ua or ""
    low = s.lower()
    if not s:
        dtype = "unknown"
    elif any(b in low for b in (
        "bot", "crawl", "spider", "slurp", "bingpreview",
        "facebookexternalhit", "headless", "lighthouse", "preview",
    )):
        dtype = "bot"
    elif "ipad" in low or "tablet" in low or ("android" in low and "mobile" not in low):
        dtype = "tablet"
    elif any(b in low for b in ("mobi", "iphone", "ipod", "android")):
        dtype = "mobile"
    else:
        dtype = "desktop"

    if any(b in low for b in ("iphone", "ipad", "ipod")) or "cpu os" in low:
        os_ = "iOS"
    elif "android" in low:
        os_ = "Android"
    elif "windows" in low:
        os_ = "Windows"
    elif "mac os" in low or "macintosh" in low:
        os_ = "macOS"
    elif "cros" in low:
        os_ = "ChromeOS"
    elif "linux" in low:
        os_ = "Linux"
    else:
        os_ = None

    if "edg" in low:
        br = "Edge"
    elif "opr" in low or "opera" in low:
        br = "Opera"
    elif "samsungbrowser" in low:
        br = "Samsung"
    elif "crios" in low or "chrome" in low:
        br = "Chrome"
    elif "fxios" in low or "firefox" in low:
        br = "Firefox"
    elif "safari" in low:
        br = "Safari"
    else:
        br = None
    return {"type": dtype, "os": os_, "browser": br}


async def _resolve_utm_clubs(db: AsyncSession, codes: set[str]) -> dict[str, dict]:
    """Map lowercased UTM codes → the marketing club that owns them.

    Clubs get a per-club ``utm_code`` for outreach links (Club Directory), so a
    visitor arriving with ``?utm_source=<code>`` is very likely that club. One
    query for the whole page of visitors."""
    codes = {c for c in codes if c}
    if not codes:
        return {}
    rows = await db.execute(
        text(
            """
            SELECT lower(utm_code) AS code, name, existing_org_id
            FROM marketing_clubs
            WHERE utm_code IS NOT NULL AND utm_code <> ''
              AND lower(utm_code) = ANY(:codes)
            """
        ),
        {"codes": list(codes)},
    )
    out: dict[str, dict] = {}
    for r in rows.mappings().all():
        out.setdefault(r["code"], {
            "name": r["name"],
            "org_id": str(r["existing_org_id"]) if r["existing_org_id"] else None,
        })
    return out


# ─── Feature categorisation (Python-side, after group-by route) ──────────────

def _categorise(route: Optional[str], path: Optional[str], event_type: str) -> str:
    s = (route or path or "").lower()
    if not s:
        return "Other"
    if event_type == "page_view":
        if s in ("/", "/features", "/pricing", "/about", "/contact",
                 "/faq", "/terms", "/privacy"):
            return "Marketing"
        if s.startswith("/blog"):
            return "Marketing — Blog"
        if s.startswith("/login"):
            return "Auth pages"
        if s.startswith("/admin"):
            return "Admin pages"
        if s.startswith("/players/"):
            return "Player profiles"
        if (s.startswith("/games/") or s.startswith("/match/")
                or s.startswith("/scorecards/")):
            return "Match pages"
        if "/yearbook" in s:
            return "Yearbooks"
        if "/leaderboard" in s:
            return "Leaderboard"
        if "/statlab" in s:
            return "StatLab"
        if "/records" in s:
            return "Records"
        if "/compare" in s:
            return "Player comparison"
        if "/dashboard" in s:
            return "Club dashboard"
        # Canonical club home: /:clubSlug (no second segment). The leading
        # slash gives one empty + one non-empty segment; reserved roots are
        # handled by earlier branches.
        parts = [p for p in s.split("?")[0].split("/") if p]
        if len(parts) == 1:
            return "Club dashboard"
        return "Other pages"
    # API
    if s.startswith("/auth"):
        return "Auth"
    if "/yearbook" in s:
        return "Yearbooks"
    if "/club-admin/players" in s or s.startswith("/players"):
        return "Players"
    if s.startswith("/games") or s.startswith("/scorecards"):
        return "Matches"
    if "/leaderboard" in s:
        return "Leaderboard"
    if "/statlab" in s:
        return "StatLab"
    if "/records" in s:
        return "Records"
    if "/sync" in s or "hard-refresh" in s:
        return "Sync / Refresh"
    if s.startswith("/club-admin"):
        return "Admin actions"
    if s.startswith("/organisations"):
        return "Organisations"
    if s.startswith("/usage"):
        return "Usage tracking"
    return "Other API"


