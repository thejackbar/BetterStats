# Highest-priority role wins when a user has multiple memberships.
# Anonymous events (no user_id) bucket as 'anon'.
ALLOWED_ROLES = ("super_admin", "club_admin", "club_member", "anon")

# Subquery that resolves a user to their single highest-priority role.
# LATERAL so it picks one row per user; ordered super > admin > member.
_USER_ROLE_JOIN = """
LEFT JOIN LATERAL (
    SELECT role
    FROM club_memberships
    WHERE user_id = ue.user_id
    ORDER BY CASE role
        WHEN 'super_admin'  THEN 0
        WHEN 'club_admin'   THEN 1
        WHEN 'club_member'  THEN 2
        ELSE 3
    END
    LIMIT 1
) cm ON ue.user_id IS NOT NULL
"""


def _normalise_roles(roles: Optional[list[str]]) -> list[str]:
    """Validate + dedupe an incoming list of role filter values.

    Accepts either a real list (FastAPI multi-`?role=` form) or a single
    comma-separated string for convenience.
    """
    if not roles:
        return []
    out: list[str] = []
    for r in roles:
        if r is None:
            continue
        for part in str(r).split(","):
            part = part.strip()
            if part in ALLOWED_ROLES and part not in out:
                out.append(part)
    return out


def _role_filter(roles: list[str]) -> str:
    """SQL fragment to AND into the WHERE clause for a multi-role filter.

    Empty string when no role filter. When `anon` is in the list it OR's
    a `user_id IS NULL` branch with the named-role IN (...) branch.
    """
    if not roles:
        return ""
    named = [r for r in roles if r != "anon"]
    include_anon = "anon" in roles
    if named and include_anon:
        return "AND (cm.role = ANY(:role_filter) OR ue.user_id IS NULL)"
    if named:
        return "AND cm.role = ANY(:role_filter)"
    # anon only
    return "AND ue.user_id IS NULL"


def _role_params(roles: list[str]) -> dict:
    named = [r for r in roles if r != "anon"]
    if named:
        return {"role_filter": named}
    return {}


def _search_clause(q: Optional[str], params: dict) -> str:
    """ANDable clause matching a free-text query against the path, route and
    UTM fields. Mutates ``params`` to add the ``:q`` bind.

    The page-view beacon stores the FULL landing URL (incl. the query string)
    in ``path``, so a search like ``utm_campaign=spring`` or ``applecross``
    matches historical rows too — not just the rows written after the dedicated
    utm_* columns existed. Empty/whitespace ``q`` → no clause."""
    if not q or not q.strip():
        return ""
    params["q"] = f"%{q.strip()}%"
    return (
        "AND (ue.path ILIKE :q OR ue.route ILIKE :q "
        "OR ue.utm_source ILIKE :q OR ue.utm_campaign ILIKE :q "
        "OR ue.utm_content ILIKE :q OR ue.utm_medium ILIKE :q)"
    )


