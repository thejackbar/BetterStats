@router.get("/club-admin/usage/summary")
async def summary(
    days: int = 7,
    role: Optional[list[str]] = Query(None),
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    days = max(1, min(days, 365))
    roles = _normalise_roles(role)
    params: dict = {"days": days, **_role_params(roles)}
    extra = []
    if event_type:
        extra.append("AND ue.event_type = :etype")
        params["etype"] = event_type
    extras = "\n".join(extra) + " " + _role_filter(roles)
    row = await db.execute(
        text(
            f"""
            SELECT
                COUNT(*)                                                            AS total,
                COUNT(*) FILTER (WHERE ue.event_type = 'api')                       AS api_hits,
                COUNT(*) FILTER (WHERE ue.event_type = 'page_view')                 AS page_views,
                COUNT(DISTINCT ue.user_id) FILTER (WHERE ue.user_id IS NOT NULL)    AS unique_users,
                COUNT(DISTINCT ue.ip_hash) FILTER (WHERE ue.ip_hash IS NOT NULL)    AS unique_ips
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {extras}
            """
        ),
        params,
    )
    r = row.mappings().first()
    return {
        "days": days,
        "total": int(r["total"] or 0),
        "api_hits": int(r["api_hits"] or 0),
        "page_views": int(r["page_views"] or 0),
        "unique_users": int(r["unique_users"] or 0),
        "unique_ips": int(r["unique_ips"] or 0),
    }


@router.get("/club-admin/usage/timeseries")
async def timeseries(
    days: int = 7,
    role: Optional[list[str]] = Query(None),
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Hits per bucket. Bucket = hour for 24h window, day for >24h."""
    days = max(1, min(days, 365))
    bucket = "hour" if days <= 1 else "day"
    roles = _normalise_roles(role)
    params: dict = {"days": days, **_role_params(roles)}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                date_trunc('{bucket}', ue.created_at) AS bucket,
                COUNT(*) FILTER (WHERE ue.event_type = 'api')        AS api_hits,
                COUNT(*) FILTER (WHERE ue.event_type = 'page_view')  AS page_views,
                COUNT(*) AS total
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            {_role_filter(roles)}
            GROUP BY bucket
            ORDER BY bucket ASC
            """
        ),
        params,
    )
    return {
        "bucket": bucket,
        "points": [
            {
                "bucket": r["bucket"].isoformat() if r["bucket"] else None,
                "api_hits": int(r["api_hits"] or 0),
                "page_views": int(r["page_views"] or 0),
                "total": int(r["total"] or 0),
            }
            for r in rows.mappings().all()
        ],
    }


@router.get("/club-admin/usage/by-feature")
async def by_feature(
    days: int = 7,
    role: Optional[list[str]] = Query(None),
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Group routes/paths into feature buckets. Bucketing is Python-side
    so the SQL stays readable; the data volume per window is small."""
    days = max(1, min(days, 365))
    roles = _normalise_roles(role)
    params: dict = {"days": days, **_role_params(roles)}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                ue.route,
                ue.path,
                ue.event_type,
                COUNT(*) AS hits
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            {_role_filter(roles)}
            GROUP BY ue.route, ue.path, ue.event_type
            """
        ),
        params,
    )
    buckets: dict[str, int] = {}
    for r in rows.mappings().all():
        feat = _categorise(r["route"], r["path"], r["event_type"])
        buckets[feat] = buckets.get(feat, 0) + int(r["hits"] or 0)
    return sorted(
        [{"feature": k, "hits": v} for k, v in buckets.items()],
        key=lambda x: x["hits"],
        reverse=True,
    )


@router.get("/club-admin/usage/by-role")
async def by_role(
    days: int = 7,
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Hit count grouped by the user's role (incl. anon)."""
    days = max(1, min(days, 365))
    params: dict = {"days": days}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                COALESCE(cm.role, 'anon') AS role,
                COUNT(*) AS hits,
                COUNT(DISTINCT ue.user_id) FILTER (WHERE ue.user_id IS NOT NULL) AS unique_users
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            GROUP BY COALESCE(cm.role, 'anon')
            ORDER BY hits DESC
            """
        ),
        params,
    )
    return [
        {
            "role": r["role"],
            "hits": int(r["hits"] or 0),
            "unique_users": int(r["unique_users"] or 0),
        }
        for r in rows.mappings().all()
    ]


@router.get("/club-admin/usage/by-club")
async def by_club(
    days: int = 7,
    role: Optional[list[str]] = Query(None),
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Usage attributed to each club.

    Two attribution paths, both query-time (so it works on existing data, no
    backfill): an event's explicit ``org_id`` when set, else — for public SPA
    page views — the club slug parsed out of the path (``/{slug}/…``). Events
    that resolve to neither (marketing pages, admin pages, API calls with no
    org context) are bucketed as ``Unattributed`` so the totals reconcile.
    """
    days = max(1, min(days, 365))
    roles = _normalise_roles(role)
    params: dict = {"days": days, **_role_params(roles)}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                COALESCE(o_org.id::text, o_slug.id::text)       AS club_id,
                COALESCE(o_org.name, o_slug.name)               AS club_name,
                COALESCE(o_org.slug, o_slug.slug)               AS club_slug,
                COUNT(*)                                        AS hits,
                COUNT(*) FILTER (WHERE ue.event_type = 'page_view') AS page_views,
                COUNT(DISTINCT ue.ip_hash) FILTER (WHERE ue.ip_hash IS NOT NULL) AS unique_ips
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            LEFT JOIN organisations o_org  ON o_org.id = ue.org_id
            LEFT JOIN organisations o_slug ON ue.org_id IS NULL
                                          AND ue.event_type = 'page_view'
                                          AND o_slug.slug = split_part(split_part(ue.path, '?', 1), '/', 2)
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            {_role_filter(roles)}
            GROUP BY 1, 2, 3
            ORDER BY hits DESC
            """
        ),
        params,
    )
    out = []
    for r in rows.mappings().all():
        out.append({
            "club_id": r["club_id"],
            "club_name": r["club_name"] or "Unattributed (marketing / admin / API)",
            "club_slug": r["club_slug"],
            "hits": int(r["hits"] or 0),
            "page_views": int(r["page_views"] or 0),
            "unique_ips": int(r["unique_ips"] or 0),
        })
    # Keep the attributed clubs first; the single Unattributed bucket sinks last.
    out.sort(key=lambda x: (x["club_id"] is None, -x["hits"]))
    return out


@router.get("/club-admin/usage/visitors")
async def visitors(
    days: int = 7,
    event_type: Optional[str] = None,
    anon_only: bool = False,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    """Return-visitor analytics keyed on the stable visitor id (falling back to
    the hashed IP for legacy rows). We never store raw IPs.

      - visitors:    distinct visitors seen in the window
      - returning:   visitors whose first-ever hit predates the window
      - new:         visitors − returning
      - multi_day:   visitors active on ≥2 distinct days in the window
      - high_intent: visitors who viewed the contact or pricing page
      - identified:  visitors carrying a real first-party id (not IP-only)
      - avg_hits:    hits per visitor
    """
    days = max(1, min(days, 365))
    params: dict = {"days": days}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    anon_clause = "AND ue.user_id IS NULL" if anon_only else ""
    row = (await db.execute(
        text(
            f"""
            WITH win AS (
                SELECT {_VKEY} AS vkey,
                       COUNT(*) AS hits,
                       COUNT(DISTINCT date_trunc('day', ue.created_at)) AS active_days,
                       bool_or(ue.visitor_id IS NOT NULL) AS identified,
                       bool_or({_INTENT_CONTACT} OR {_INTENT_PRICING}) AS high_intent
                FROM usage_events ue
                WHERE {_VKEY} IS NOT NULL
                  AND ue.created_at >= NOW() - (:days * INTERVAL '1 day')
                  {type_clause}
                  {anon_clause}
                GROUP BY {_VKEY}
            ),
            first_seen AS (
                SELECT {_VKEY} AS vkey, MIN(ue.created_at) AS first_ever
                FROM usage_events ue
                WHERE {_VKEY} IN (SELECT vkey FROM win)
                GROUP BY {_VKEY}
            )
            SELECT
                (SELECT COUNT(*) FROM win)                                  AS visitors,
                (SELECT COUNT(*) FROM win WHERE active_days >= 2)           AS multi_day,
                (SELECT COUNT(*) FROM win WHERE high_intent)               AS high_intent,
                (SELECT COUNT(*) FROM win WHERE identified)                AS identified,
                (SELECT COALESCE(SUM(hits), 0) FROM win)                    AS total_hits,
                (SELECT COUNT(*) FROM first_seen
                  WHERE first_ever < NOW() - (:days * INTERVAL '1 day'))    AS returning
            """
        ),
        params,
    )).mappings().first()
    visitors_n = int(row["visitors"] or 0)
    returning_n = int(row["returning"] or 0)
    total_hits = int(row["total_hits"] or 0)
    return {
        "days": days,
        "visitors": visitors_n,
        "returning": returning_n,
        "new": max(visitors_n - returning_n, 0),
        "multi_day": int(row["multi_day"] or 0),
        "high_intent": int(row["high_intent"] or 0),
        "identified": int(row["identified"] or 0),
        "total_hits": total_hits,
        "avg_hits": round(total_hits / visitors_n, 1) if visitors_n else 0.0,
        "returning_pct": round(100 * returning_n / visitors_n) if visitors_n else 0,
    }


@router.get("/club-admin/usage/top-routes")
async def top_routes(
    days: int = 7,
    limit: int = 30,
    role: Optional[list[str]] = Query(None),
    event_type: Optional[str] = None,
    _: User = Depends(require_super_admin),
    db: AsyncSession = Depends(get_db),
):
    days = max(1, min(days, 365))
    limit = max(1, min(limit, 200))
    roles = _normalise_roles(role)
    params: dict = {"days": days, "lim": limit, **_role_params(roles)}
    type_clause = ""
    if event_type:
        type_clause = "AND ue.event_type = :etype"
        params["etype"] = event_type
    rows = await db.execute(
        text(
            f"""
            SELECT
                COALESCE(ue.route, ue.path) AS route_key,
                ue.event_type,
                COUNT(*) AS hits,
                COUNT(DISTINCT ue.user_id) FILTER (WHERE ue.user_id IS NOT NULL) AS unique_users,
                COUNT(DISTINCT ue.ip_hash) FILTER (WHERE ue.ip_hash IS NOT NULL) AS unique_ips,
                MAX(ue.created_at) AS last_hit
            FROM usage_events ue
            {_USER_ROLE_JOIN}
            WHERE ue.created_at >= NOW() - (:days * INTERVAL '1 day')
            {type_clause}
            {_role_filter(roles)}
            GROUP BY route_key, ue.event_type
            ORDER BY hits DESC
            LIMIT :lim
            """
        ),
        params,
    )
