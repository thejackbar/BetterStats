# ─── Target-name resolution ──────────────────────────────────────────────────

# Frontend SPA paths whose first UUID is a player. Match `path`, not `route`.
_PLAYER_PATH_RES = (
    re.compile(r"^/players/([0-9a-f-]{36})", re.IGNORECASE),
)
_GAME_PATH_RES = (
    re.compile(r"^/games/([0-9a-f-]{36})", re.IGNORECASE),
    re.compile(r"^/match/([0-9a-f-]{36})", re.IGNORECASE),
    re.compile(r"^/scorecards/([0-9a-f-]{36})", re.IGNORECASE),
)


def _extract_target(path: Optional[str]) -> tuple[Optional[str], Optional[str]]:
    """Return (kind, uuid) for paths that point at a known entity.

    `kind` is one of 'player', 'game'. None if no match.
    """
    if not path:
        return (None, None)
    for r in _PLAYER_PATH_RES:
        m = r.match(path)
        if m:
            return ("player", m.group(1).lower())
    for r in _GAME_PATH_RES:
        m = r.match(path)
        if m:
            return ("game", m.group(1).lower())
    return (None, None)


async def _enrich_targets(db: AsyncSession, rows: list[dict]) -> list[dict]:
    """Attach `target_name` + `target_url` for rows whose path points at
    a known player or game. Two extra queries total (one per kind)."""
    player_ids: set[str] = set()
    game_ids: set[str] = set()
    for r in rows:
        kind, tid = _extract_target(r.get("path"))
        if kind == "player":
            player_ids.add(tid)
        elif kind == "game":
            game_ids.add(tid)

    player_names: dict[str, str] = {}
    if player_ids:
        result = await db.execute(
            text(
                "SELECT id, COALESCE(display_name_override, name) AS name "
                "FROM players WHERE id = ANY(:ids)"
            ),
            {"ids": [_uuid.UUID(x) for x in player_ids]},
        )
        for row in result.mappings().all():
            player_names[str(row["id"]).lower()] = row["name"]

    game_summaries: dict[str, str] = {}
    if game_ids:
        result = await db.execute(
            text(
                """
                SELECT g.id,
                       g.played_at,
                       g.home_team,
                       g.away_team
                FROM games g
                WHERE g.id = ANY(:ids)
                """
            ),
            {"ids": [_uuid.UUID(x) for x in game_ids]},
        )
        for row in result.mappings().all():
            home = row["home_team"] or "?"
            away = row["away_team"] or "?"
            when = row["played_at"].strftime("%d %b %Y") if row["played_at"] else ""
            game_summaries[str(row["id"]).lower()] = f"{home} v {away} · {when}".strip(" ·")

    out = []
    for r in rows:
        kind, tid = _extract_target(r.get("path"))
        target_name = None
        target_url = None
        if kind == "player" and tid in player_names:
            target_name = player_names[tid]
            target_url = f"/players/{tid}"
        elif kind == "game" and tid in game_summaries:
            target_name = game_summaries[tid]
            target_url = f"/games/{tid}"
        out.append({
            "id": r["id"],
            "created_at": r["created_at"].isoformat() if r["created_at"] else None,
            "event_type": r["event_type"],
            "method": r["method"],
            "path": r["path"],
            "route": r["route"],
            "status": r["status"],
            "duration_ms": r["duration_ms"],
            "user_id": str(r["user_id"]) if r["user_id"] else None,
            "user_email": r["user_email"],
            "user_display_name": r["user_display_name"],
            "user_role": r["user_role"],
            "ip_hash": r["ip_hash"],
            "referer": r["referer"],
            "country": r["country"],
            "region": r["region"],
            "city": r["city"],
            "target_kind": kind,
            "target_name": target_name,
            "target_url": target_url,
        })
    return out


